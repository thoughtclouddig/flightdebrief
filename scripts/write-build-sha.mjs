// Regenerates lib/build-info.generated.ts with the current git commit's
// short SHA, run automatically before `dev`/`build`/`test` (see package.json's
// predev/prebuild/pretest scripts). Investigated first: no environment in
// this repo (Development, Staging, or Production Replit deployments) sets
// its own build/commit-SHA env var today -- see lib/build-info.ts's own doc
// comment. This is the smallest mechanism that gets a real, non-hardcoded
// value onto disk before the app needs it, in every environment that runs
// `npm run build` (which is exactly how each Repl builds itself, per
// .replit's own `[deployment] build = ["npm", "run", "build"]`).
import { execSync } from "node:child_process";
import { writeFileSync } from "node:fs";

function resolveBuildSha() {
  try {
    return execSync("git rev-parse --short=9 HEAD", { encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }).trim() || null;
  } catch {
    // No .git present (e.g. a stripped deployment artifact) -- an honest
    // null is better than a stale or fabricated value.
    return null;
  }
}

const sha = resolveBuildSha();
const contents = `// Auto-generated by scripts/write-build-sha.mjs before dev/build/test --
// do not hand-edit. The checked-in value is a placeholder; every real
// dev/build/test run overwrites it with the actual current commit.
export const BUILD_SHA: string | null = ${sha ? JSON.stringify(sha) : "null"};
`;

writeFileSync(new URL("../lib/build-info.generated.ts", import.meta.url), contents);
